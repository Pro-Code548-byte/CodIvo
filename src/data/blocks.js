export function getBlockDef(id) {
  return blockRegistry[id]
}

const EXTRA_ATTRS = {
  a: ['href'],
  img: ['src', 'alt'],
  input: ['type', 'placeholder'],
  option: ['value'],
}

for (const def of Object.values(blockRegistry)) {
  def.attrs = [...(EXTRA_ATTRS[def.id] ?? []), 'class', 'id']
}

export function isVoid(id) {
  return !!(blockRegistry[id]?.voidElement)
}